#
# ══════════════════════════════════════════════════════════════════════
# v2 (ガラスベル/Meta グラス調) から v3 で何を捨てたか、なぜか
# ══════════════════════════════════════════════════════════════════════
# 前提: これは頭に装着して騒音下の現場で使うアプリのフィードバック音。
#       「良い音」ではなく「騒音の中で聞き分けられる音」が要件。
#       v2 のリッチ路線は、その要件に対しては全項目が逆方向に効いていた。
#
#   ✗ リバーブ (IR 畳み込み / プリディレイ / 初期反射) → 全撤去。
#     残響は音の輪郭を溶かす。現場の反射音とも混ざる。効果音の識別性能を最も落とす要素。
#     代わりに「NES エコー」(同じ音を少し後ろに小音量で重ねる) を用意した。実機に無い
#     残響を音符で偽装する、当時のトラッカーの手口。輪郭が保たれるので騒音下でも死なない。
#   ✗ ステレオ (左右別 IR) → モノに変更。
#     骨伝導/オープンイヤーは実質モノだし、片耳運用や装着ズレで音像が壊れるのを避ける。
#   ✗ ソフトアタック (raised cosine 10ms) → 即時立ち上げ (クリック防止の 1ms のみ)。
#     立ち上がりが鈍い音は騒音にマスクされる。検知も方向定位も遅れる。
#   ✗ サブオクターブ / A3・D4 の「土台」ノート → 削除。
#     低域は現場騒音 (機械・風・空調) の本拠地で、まず通らない。骨伝導では再生すらされない。
#     鳴らないのに RMS 正規化のヘッドルームだけ食うので、純粋な損。
#     ※温かみ目的の三角波ベースは入場チャイムにだけ残した (あそこだけ識別要件が無いので)。
#   ✗ ノイズ (帯域ノイズのマレット「息」、ガラスのモード) → 削除。
#     NES のノイズチャンネルも使っていない。理由は同じで、広帯域ノイズは現場騒音と
#     スペクトル形状が一致するため、埋もれるうえに環境音と誤認される。
#     警告こそノイズではなくパルス波でやるべき。
#   ✗ 非整数倍音のガラス質感 → 矩形/パルス波の整数倍音に。
#     パルス波は倍音が上まで密に並ぶので、一部の帯域がマスクされても他の倍音が生き残る。
#     騒音下で残るのは「音色」ではなく「ピッチ輪郭 × 音数 × 減衰の有無」。そこで設計する。
#
# ══════════════════════════════════════════════════════════════════════
# 識別の設計 (騒音下で最後まで残る 3 軸だけで区別する)
# ══════════════════════════════════════════════════════════════════════
#   軸1: 音数        1 / 2 / 3 / 4 / 5
#   軸2: ピッチ輪郭  上昇 / 下降 / 交互
#   軸3: 減衰の有無  減衰する (= 確認系) / 減衰しない持続音 (= 警告のみ)
#
#   刻み      1 音              50% duty         短い単発
#   パー確定  2 音 上昇 (C#5→A5) 12.5% duty      I  (トニックに着地 = 確定)
#   停止      2 音 下降 (E6→A5) 50% duty・36ms 間隔  I  (パー確定の鏡像。下降 = 閉じる)
#   グッド    3 音 上昇 (E5→F#5→B5) 12.5% duty   B5 (9th) で開く = 終止は rec_stop に渡す
#   go        4 音 上昇 + アルペジオ和音          I  で離陸
#   入場      5 音 ロール + 三角波ベース          I  の Amaj9
#   警告      2 音 交互 × 2 往復・持続・下降で終端 12.5% duty・三全音
#
#   停止とパー確定はどちらも 2 音・トニック着地だが、輪郭が上昇/下降で真逆。
#   さらに停止の 36ms 間隔は全 7 音で最短 (次に短いのが 45ms) なので、リズムだけでも一意。
#   duty 50% = 「機械/トランスポート系」(刻み・go の拍頭・停止) というグループ分けにもなっている。
#
#   duty (音色) の差は「おまけ」。騒音下で真っ先に潰れるのは音色なので、そこには頼らない。
#   音数と輪郭だけで全部区別がつくようになっている。
#
# ══════════════════════════════════════════════════════════════════════
# 警告音の扱い ⚠ 設計上の境界
# ══════════════════════════════════════════════════════════════════════
#   warn_hand_lost は「手が見えない」= 操作上の注意であって、安全に関わる危険通知ではない。
#   この前提でレトロ路線に入れてある (持続音 + 三全音 + 高めの音量で、確認系とは別物に聞こえる)。
#   もし今後、人身・設備の危険に関わるアラートを追加するなら、この系統に混ぜないこと。
#   ピコピコ音は軽く受け取られる。危険通知は ISO 7731 相当の別系統に分離する。
#
# ══════════════════════════════════════════════════════════════════════
# いじる場所
# ══════════════════════════════════════════════════════════════════════
#   OCTAVE_SHIFT  現場でマスクされるなら +1 にして A/B すること (下のコメント参照)
#   SOUNDS        各効果音の音符定義。n(...) ヘルパで 1 音 = 1 行
#   TARGET_RMS / MASTER_PEAK / NES_HP / NES_LP  全体の質感

