# NOTE: 撮影終了フロー (グッド検知 → 2 秒キープ → 停止) での鳴らし方
# ══════════════════════════════════════════════════════════════════════
# このスクリプトは音を 1 つずつ作るだけ。並べるのはアプリ側なので、意図をここに残す。
#
# ◆ 2 秒キープ中に必ず刻みを鳴らすこと。無音にしない。
#   刻みが無いと、ユーザーは「検知された」以降 2 秒間、成立しているのか・あと何秒なのかを
#   知る手段が無い。腕を上げたまま 2 秒は現場では長い。刻みはこのために存在している
#   (音楽的にも V = 属音のペダル = 溜め。解決を待っている状態を表す)。
#
# ◆ 刻みは等間隔。0.50s / 1.00s / 1.50s → 2.00s で rec_stop (ユーザー確定)。
#   刻み 3 発で終わり、と数で覚えてもらう設計。刻みは 75ms なので 2 秒間に十分収まる。
#   ※加速 (間隔を詰めていく) 案もあったが不採用。等間隔で固定すること。
#
# ◆ rec_stop の 1 音目は刻みと同じ E6/50% duty にしてある (countdown_end_go も同じ)。
#   刻みのリズムが途切れずに停止音へ流れ込む。偶然ではなく、そう作ってある。
#
# ◆ 開始と終了は「同じ溜め・逆の解決」で対になっている:
#     刻み (E6 = V で溜め) → go   : A へ上昇して解決 = 始まる
#     刻み (E6 = V で溜め) → stop : A へ下降して解決 = 終わる
#   刻み自体はどちらか分からなくてよい。答えは解決の向きが持っている。
#   録画中かどうかは本人が知っているので、文脈で曖昧さは消える。
#
# ◆ キープ中に姿勢が崩れたら detect_cancel_blip を鳴らして刻みを止める。
#   崩れたのに無音だと、中断されたのか継続中なのか分からない。
#   手ごと消えた場合は warn_hand_lost (異常) 、ジェスチャーだけ解けた場合は cancel (正常)。
#
# ◆ グッド確定は主音に着地させず B5 (9th) で開く。
#   ここは終了シーケンスの入口で、まだ何も終わっていない。主音 A5 に着地 (= 終止) させると、
#   2 秒後の rec_stop (A5) と合わせて 1 操作に終止が 2 回でき「どっちが本当の終了?」が濁る。
#   グッドを開いておけば グッド (B5 開く) → 刻み (E6 溜め) → stop (A5 閉じる) で終止は
#   rec_stop の 1 回だけ。パー確定 (A5 着地) と非対称になるのは意図どおり: パーは「合った」を
#   確定して保持、グッドはこの後カウント → 停止が続くので開けておく。