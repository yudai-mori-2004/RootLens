#   短い確定音 (palm/thumbs) では融合せず「音数が増えた」と聞こえる。実際にそう指摘された。
#   それらの帯域は arp ではなく duty 12.5% で散らすこと (§duty)。


def n(f, at, dur, amp=1.0, duty=D25, decay=0.08, hold=None, bend=0.0,
      arp=None, ch="pulse"):
    """音符 1 個。
      f     基音 (Hz)
      at    開始 (秒) / dur 長さ (秒) / amp 音量 (0..1 相対)
      duty  D12 / D25 / D50。パルス波の太さ
      decay 減衰時定数 (秒)。小さいほどコツンと切れる
      hold  指定するとその秒数だけ減衰せず鳴りっぱなし → 警告用。decay は無視される
      bend  ノート内で何半音ベンドするか (実機同様に周期に対して線形 = 階段状)
      arp   半音オフセットのリスト。ARP_RATE で巡回して和音に聞かせる古典アルペジオ
      ch    "pulse" (パルス波) / "tri" (三角波。ベース用・音量固定)
    """
    return dict(f=f, at=at, dur=dur, amp=amp, duty=duty, decay=decay,
                hold=hold, bend=bend, arp=arp, ch=ch)


