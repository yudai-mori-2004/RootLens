# ─── 合成の中身 ────────────────────────────────────────────────────────


def _shift(f: float) -> float:
    return f * (2.0 ** OCTAVE_SHIFT)


def _nes_freq(f: np.ndarray, div: int) -> np.ndarray:
    """周波数を実機の 11bit 周期レジスタに丸める (高音ほどズレる = レトロの味)。"""
    if not PITCH_QUANTIZE:
        return f
    p = np.round(NES_CPU / (div * np.maximum(f, 1.0)) - 1.0)
    p = np.clip(p, 8.0, 2047.0)
    return NES_CPU / (div * (p + 1.0))


def _blip_pulse(phase: np.ndarray, duty: float, fmax: float) -> np.ndarray:
    """帯域制限パルス波 (フーリエ級数)。ナイキストを超える倍音を出さない = 汚い折り返しが無い。
    duty=0.5 なら奇数倍音のみ = 矩形波。"""
    kmax = max(1, int(0.45 * SR / max(fmax, 1.0)))
    y = np.zeros(len(phase))
    for k in range(1, kmax + 1):
        a = np.sin(np.pi * k * duty)
        if abs(a) < 1e-9:
            continue
        y += (2.0 / (k * np.pi)) * a * np.cos(TWO_PI * k * phase)
    return y


def _blip_tri(phase: np.ndarray, fmax: float) -> np.ndarray:
    """帯域制限三角波 → 16 段に量子化。実機の三角波はこの階段が音色そのもの。"""
    kmax = max(1, int(0.45 * SR / max(fmax, 1.0)))
    y = np.zeros(len(phase))
    for k in range(1, kmax + 1, 2):
        y += (8.0 / (np.pi ** 2 * k ** 2)) * ((-1) ** ((k - 1) // 2)) \
             * np.sin(TWO_PI * k * phase)
    return np.round(y * 7.5) / 7.5


def _env(t: np.ndarray, decay: float, hold: float | None) -> np.ndarray:
    """4bit / 240Hz 更新の階段エンベロープ。実機に無いソフトアタックは付けない。"""
    tq = np.floor(t * ENV_RATE) / ENV_RATE
    e = (tq < hold).astype(float) if hold else np.exp(-tq / decay)
    return np.clip(np.round(e * (VOL_STEPS - 1)), 0, VOL_STEPS - 1) / (VOL_STEPS - 1)


def _declick(y: np.ndarray) -> np.ndarray:
    """1ms のランプ。実機には無いが、DAC/MP3 のプチッを消すためだけの保険。
    立ち上がりの鋭さは犠牲にならない長さ。"""
    r = min(int(SR * 0.001), len(y) // 2)
    if r > 1:
        y[:r] *= np.linspace(0.0, 1.0, r)
        y[-r:] *= np.linspace(1.0, 0.0, r)
    return y


def note(p: dict) -> np.ndarray:
    freq = _shift(p["f"])
    nsamp = int(SR * p["dur"])
    t = np.arange(nsamp) / SR
    div = 32 if p["ch"] == "tri" else 16

    # ピッチベンド: 実機のスウィープは周波数ではなく「周期」に対して線形に動く
    if p["bend"]:
        tq = np.floor(t * SWEEP_RATE) / SWEEP_RATE
        p0 = NES_CPU / (div * freq) - 1.0
        p1 = NES_CPU / (div * (freq * 2.0 ** (p["bend"] / 12.0))) - 1.0
        pt = p0 + (p1 - p0) * np.clip(tq / p["dur"], 0.0, 1.0)
        f_t = NES_CPU / (div * (pt + 1.0))
    else:
        f_t = np.full(nsamp, freq)

    # アルペジオ: 1 フレームごとに音を切り替えて和音に聞かせる
    if p["arp"]:
        step = np.floor(t * ARP_RATE).astype(int) % len(p["arp"])
        f_t = f_t * (2.0 ** (np.asarray(p["arp"], dtype=float)[step] / 12.0))

    f_t = _nes_freq(f_t, div)
    phase = np.cumsum(f_t) / SR

    if p["ch"] == "tri":
        y = _blip_tri(phase, float(f_t.max()))
        gate = _env(t, p["dur"] * 0.5, None)  # 実機の三角波は音量固定。ゲートで代用
        y = y * (gate > 0)
    else:
        y = _blip_pulse(phase, p["duty"], float(f_t.max()))
        y = y * _env(t, p["decay"], p["hold"])

    return _declick(y * p["amp"])


def render(spec: dict) -> np.ndarray:
    notes = spec["notes"]
    total = max(p["at"] + p["dur"] for p in notes)
    delay, gain = spec.get("echo", (0.0, 0.0))
    y = np.zeros(int(SR * (total + delay + 0.02)) + 1)
    for p in notes:
        s = note(p)
        i = int(SR * p["at"])
        end = min(len(y), i + len(s))
        y[i:end] += s[: end - i]
    if gain:
        # NES エコー: リバーブではなく「同じ音を少し後ろで小さく鳴らす」当時の手口。
        # 輪郭が溶けないので騒音下でも識別性が落ちない。
        d = int(SR * delay)
        y[d:] += gain * y[: len(y) - d]
    return y


def _fft_band(y: np.ndarray, lo: float | None = None, hi: float | None = None) -> np.ndarray:
    """FFT で緩やかな帯域制限 (2 次相当の肩)。"""
    n = len(y)
    spec = np.fft.rfft(y)
    f = np.fft.rfftfreq(n, 1.0 / SR)
    g = np.ones_like(f)
    if lo:
        g *= 1.0 / (1.0 + (lo / np.maximum(f, 1e-6)) ** 4)
    if hi:
        g *= 1.0 / (1.0 + (f / hi) ** 4)
    return np.fft.irfft(spec * g, n)


def write_mp3(y: np.ndarray, out_mp3: str, target_rms: float = TARGET_RMS) -> None:
    # 実機の RC フィルタ相当。低域を捨てて中高域に寄せる = 騒音下で通る方向でもある
    y = _fft_band(y, lo=NES_HP, hi=NES_LP)

    # ラウドネス正規化: RMS_WINDOW の実効値の最大を target_rms に合わせる
    w = max(1, int(SR * RMS_WINDOW))
    power = np.convolve(y ** 2, np.ones(w) / w, mode="same")
    y = y * (target_rms / max(1e-9, np.sqrt(power.max())))
    peak = np.abs(y).max()
    if peak > MASTER_PEAK:
        y = y * (MASTER_PEAK / peak)

    # 聞こえない尾をトリム (ピーク比 -66dB を下回った点まで + 20ms 余白)
    envelope = np.abs(y)
    last = int(np.argwhere(envelope > envelope.max() * 10 ** (-66 / 20)).max())
    y = y[: min(len(y), last + int(SR * 0.02))]

    fade = int(SR * 0.003)
    y[:fade] *= np.linspace(0, 1, fade)
    y[-fade:] *= np.linspace(1, 0, fade)
    pcm = (np.clip(y, -1.0, 1.0) * 32767).astype(np.int16)
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        with wave.open(tmp.name, "wb") as wv:
            wv.setnchannels(1)   # モノ: 骨伝導/オープンイヤー/片耳運用で音像が壊れない
            wv.setsampwidth(2)
            wv.setframerate(SR)
            wv.writeframes(pcm.tobytes())
        subprocess.run(
            ["ffmpeg", "-y", "-v", "error", "-i", tmp.name,
             "-codec:a", "libmp3lame", "-b:a", "192k", "-ar", "44100", "-ac", "1", out_mp3],
            check=True,
        )
    os.unlink(tmp.name)


def main() -> None:
    repo_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out_dir = os.environ.get("SFX_OUT") or os.path.join(repo_root, "app", "assets", "sounds")
    os.makedirs(out_dir, exist_ok=True)
    only = sys.argv[1] if len(sys.argv) > 1 else None
    for name, spec in SOUNDS.items():
        if only and only not in name:
            continue
        out = os.path.join(out_dir, f"{name}.mp3")
        write_mp3(render(spec), out, target_rms=spec.get("rms", TARGET_RMS))
        print(f"wrote {out}")


if __name__ == "__main__":
    main()


